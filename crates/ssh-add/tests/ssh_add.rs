#[test]
fn locking() {
    let openssh = require_openssh!();
    let fixtures = fixtures(&openssh);
    let cases: &[(&[&str], &str)] = &[
        (&["-x"], "secret\nsecret\n"),
        (&["-x"], "a\nb\n"),
        (&["-X"], "secret\n"),
    ];
    for (args, stdin) in cases {
        case(&openssh, &fixtures, &["plain"], args, stdin)
            .assert_same_outcome()
            .assert_same_agent(&openssh);
    }

    // Unlocking with the right and the wrong password.
    for password in ["secret\n", "wrong\n"] {
        let c = ssh_add(&openssh)
            .case(["-X"])
            .agent(&openssh)
            .setup(|dir| {
                install(fixtures.path(), dir);
                preload(&openssh, dir, &["plain"]);
                let out = run(
                    command(openssh.require_tool("ssh-add"), dir)
                        .env("SSH_AUTH_SOCK", dir.join(AGENT_SOCKET))
                        .arg("-x"),
                    b"secret\nsecret\n",
                );
                assert_eq!(out.status, Some(0), "{}", out.stderr);
            })
            .stdin(password)
            .run();
        c.assert_same_outcome().assert_same_agent(&openssh);
    }
}

