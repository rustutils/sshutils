//! `ssh-add` compared against OpenSSH's. Each run gets its own fresh
//! OpenSSH `ssh-agent`; besides exit status and stdout, the tests compare
//! what the agents hold afterwards.

use std::fs;
use std::os::unix::fs::PermissionsExt;
use std::path::Path;
use std::thread;
use std::time::Duration;

use sshutils_testing::{
    AGENT_SOCKET, Comparison, Differential, Openssh, Outcome, command, require_openssh, run,
};
use tempfile::TempDir;

const OURS: &str = env!("CARGO_BIN_EXE_ssh-add");

fn ssh_add(openssh: &Openssh) -> Differential {
    Differential::new(OURS, openssh.require_tool("ssh-add"))
}

/// Keys generated by OpenSSH:
///
/// - `plain`, `rsa`, `nocomment` (empty comment): unencrypted
/// - `enc`, `enc2`: encrypted with passphrase `pw`
/// - `user` + `user-cert.pub`: certificate without expiry
/// - `short` + `short-cert.pub`: certificate valid for another hour
/// - `old` + `old-cert.pub`: expired certificate
/// - `mis` + `mis-cert.pub`: certificate for a different key
/// - `pem`: RSA key in PEM format
/// - `open`: unencrypted, mode 0644 (rejected)
fn fixtures(openssh: &Openssh) -> TempDir {
    let dir = tempfile::tempdir().unwrap();
    let d = dir.path();
    let keygen = |args: &[&str]| {
        let out = run(
            command(openssh.require_tool("ssh-keygen"), d).args(args),
            b"",
        );
        assert_eq!(out.status, Some(0), "{args:?}: {}", out.stderr);
    };
    let new_key = |name: &str, passphrase: &str, comment: &str| {
        keygen(&[
            "-q", "-t", "ed25519", "-N", passphrase, "-C", comment, "-f", name,
        ]);
    };
    new_key("plain", "", "plain comment");
    new_key("nocomment", "", "");
    new_key("enc", "pw", "encrypted");
    new_key("enc2", "pw", "encrypted too");
    new_key("ca", "", "ca");
    new_key("user", "", "certified");
    new_key("short", "", "short");
    new_key("old", "", "old");
    new_key("mis", "", "mis");
    new_key("open", "", "open");
    keygen(&[
        "-q", "-t", "rsa", "-b", "1024", "-N", "", "-C", "rsa", "-f", "rsa",
    ]);
    keygen(&[
        "-q", "-t", "rsa", "-b", "1024", "-m", "PEM", "-N", "", "-f", "pem",
    ]);
    keygen(&["-q", "-s", "ca", "-I", "user-id", "-n", "alice", "user.pub"]);
    keygen(&[
        "-q",
        "-s",
        "ca",
        "-I",
        "short-id",
        "-n",
        "alice",
        "-V",
        "+1h",
        "short.pub",
    ]);
    keygen(&[
        "-q",
        "-s",
        "ca",
        "-I",
        "old-id",
        "-n",
        "alice",
        "-V",
        "20200101:20200102",
        "old.pub",
    ]);
    fs::copy(d.join("user-cert.pub"), d.join("mis-cert.pub")).unwrap();
    write_askpass_programs(d);
    fs::set_permissions(d.join("open"), fs::Permissions::from_mode(0o644)).unwrap();
    dir
}

/// Askpass programs: `ok.sh` answers `pw`, `cancel.sh` cancels. Both log
/// how they were called to `askpass.log`.
fn write_askpass_programs(dir: &Path) {
    let programs = [
        (
            "ok.sh",
            "#!/bin/sh\nprintf 'args=[%s] hint=[%s]\\n' \"$*\" \"$SSH_ASKPASS_PROMPT\" >> askpass.log\necho pw\n",
        ),
        (
            "cancel.sh",
            "#!/bin/sh\nprintf 'cancelled [%s]\\n' \"$*\" >> askpass.log\nexit 1\n",
        ),
    ];
    for (name, script) in programs {
        fs::write(dir.join(name), script).unwrap();
        fs::set_permissions(dir.join(name), fs::Permissions::from_mode(0o755)).unwrap();
    }
}

/// Copy every fixture into `dir`, keeping file modes.
fn install(fixtures: &Path, dir: &Path) {
    for entry in fs::read_dir(fixtures).unwrap() {
        let entry = entry.unwrap();
        fs::copy(entry.path(), dir.join(entry.file_name())).unwrap();
    }
}

/// Load keys into the run's agent with OpenSSH's ssh-add.
fn preload(openssh: &Openssh, dir: &Path, keys: &[&str]) {
    if keys.is_empty() {
        return;
    }
    let out = openssh_ssh_add(openssh, dir, keys);
    assert_eq!(out.status, Some(0), "preloading {keys:?}: {}", out.stderr);
}

/// Run OpenSSH's ssh-add against the agent in `dir`.
fn openssh_ssh_add(openssh: &Openssh, dir: &Path, args: &[&str]) -> Outcome {
    run(
        command(openssh.require_tool("ssh-add"), dir)
            .env("SSH_AUTH_SOCK", dir.join(AGENT_SOCKET))
            .args(args),
        b"",
    )
}

/// Run a case with fixtures installed and `preloaded` keys in each agent.
fn case(
    openssh: &Openssh,
    fixtures: &TempDir,
    preloaded: &[&str],
    args: &[&str],
    stdin: &str,
) -> Comparison {
    ssh_add(openssh)
        .case(args)
        .agent(openssh)
        .setup(|dir| {
            install(fixtures.path(), dir);
            preload(openssh, dir, preloaded);
        })
        .stdin(stdin)
        .run()
}

#[test]
fn adding_keys() {
    let openssh = require_openssh!();
    let fixtures = fixtures(&openssh);
    let cases: &[(&[&str], &str)] = &[
        (&["plain"], ""),
        (&["rsa", "user"], ""),
        (&["nocomment"], ""),
        (&["pem"], ""),
        (&["-q", "plain"], ""),
        (&["enc"], "pw\n"),
        (&["enc"], "bad\npw\n"),
        (&["enc"], ""),
        (&["enc"], "bad\n"),
        (&["enc", "plain", "enc2"], "pw\n"),
        (&["missing"], ""),
        (&["open"], ""),
        (&["plain", "missing", "rsa"], ""),
        (&["-"], ""),
        (&["-t", "60", "plain"], ""),
        (&["-t", "1h30m", "-c", "rsa"], ""),
        (&["-t", "bogus", "plain"], ""),
        (&["short"], ""),
        (&["-N", "short"], ""),
        (&["-t", "60", "short"], ""),
        (&["-C", "short"], ""),
        (&["-C", "plain"], ""),
        (&["-k", "user"], ""),
        (&["old"], ""),
        (&["mis"], ""),
        (&["-M", "5", "-m", "5", "plain"], ""),
    ];
    for (args, stdin) in cases {
        case(&openssh, &fixtures, &[], args, stdin)
            .assert_same_outcome()
            .assert_same_agent(&openssh);
    }
}

