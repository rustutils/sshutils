#[test]
fn without_an_agent() {
    let openssh = require_openssh!();
    for (socket, args) in [
        (None, &["-l"][..]),
        (Some("missing.sock"), &["-l"]),
        (None, &["-T"]),
    ] {
        let differential = ssh_add(&openssh);
        let mut case = differential.case(args);
        if let Some(socket) = socket {
            case = case.env("SSH_AUTH_SOCK", socket);
        }
        case.run().assert_same_outcome();
    }
}

/// Constraints aren't visible in listings, so check their effects.
#[test]
fn constraints_take_effect() {
    let openssh = require_openssh!();
    let fixtures = fixtures(&openssh);

    // A one-second lifetime: the key is gone shortly after.
    let c = case(&openssh, &fixtures, &[], &["-t", "1", "plain"], "");
    c.assert_same_outcome();
    thread::sleep(Duration::from_secs(2));
    c.assert_same_agent(&openssh);
    let agent = c.ours.agent.as_ref().unwrap();
    assert_eq!(agent.identities(&openssh), "", "key outlived its lifetime");

    // Confirmation required: without a way to ask, the agent refuses to sign.
    let c = case(&openssh, &fixtures, &[], &["-c", "plain"], "");
    c.assert_same_outcome();
    for run in [&c.ours, &c.theirs] {
        let out = openssh_ssh_add(&openssh, run.dir.path(), &["-T", "plain.pub"]);
        assert_eq!(out.status, Some(1), "signing should need confirmation");
    }
}

#[test]
fn askpass() {
    let openssh = require_openssh!();
    let fixtures = fixtures(&openssh);
    // (environment, stdin)
    let cases: &[(&[(&str, &str)], &str)] = &[
        (&[("DISPLAY", ":0"), ("SSH_ASKPASS", "./ok.sh")], ""),
        (&[("SSH_ASKPASS", "./ok.sh")], ""),
        (
            &[("SSH_ASKPASS", "./ok.sh"), ("SSH_ASKPASS_REQUIRE", "force")],
            "",
        ),
        (
            &[("SSH_ASKPASS", "./ok.sh"), ("SSH_ASKPASS_REQUIRE", "FORCE")],
            "",
        ),
        (
            &[
                ("DISPLAY", ":0"),
                ("SSH_ASKPASS", "./ok.sh"),
                ("SSH_ASKPASS_REQUIRE", "never"),
            ],
            "pw\n",
        ),
        (
            &[
                ("DISPLAY", ":0"),
                ("SSH_ASKPASS", "./ok.sh"),
                ("SSH_ASKPASS_REQUIRE", "prefer"),
            ],
            "",
        ),
        (
            &[
                ("SSH_ASKPASS", "./ok.sh"),
                ("SSH_ASKPASS_REQUIRE", "prefer"),
            ],
            "",
        ),
        (&[("DISPLAY", ""), ("SSH_ASKPASS", "./ok.sh")], ""),
        (&[("DISPLAY", ":0"), ("SSH_ASKPASS", "./cancel.sh")], ""),
        (&[("DISPLAY", ":0"), ("SSH_ASKPASS", "./missing.sh")], ""),
    ];
    for (env, stdin) in cases {
        let differential = ssh_add(&openssh);
        let mut case = differential
            .case(["enc", "enc2"])
            .agent(&openssh)
            .setup(|dir| install(fixtures.path(), dir))
            .stdin(*stdin);
        for (key, value) in *env {
            case = case.env(*key, *value);
        }
        case.run()
            .assert_same_outcome()
            .assert_same_agent(&openssh)
            .assert_same_file("askpass.log");
    }
}
