//! `ssh-agent` compared against OpenSSH's: the same sequences of `ssh-add`
//! commands run against each agent must give the same results.

use std::fs;
use std::io::{BufRead, BufReader};
use std::os::unix::fs::PermissionsExt;
use std::path::{Path, PathBuf};
use std::process::Stdio;
use std::thread;
use std::time::Duration;

use sshutils_testing::{Agent, Differential, Openssh, Outcome, command, require_openssh, run};
use tempfile::TempDir;

const OURS: &str = env!("CARGO_BIN_EXE_ssh-agent");

/// One step of a session: an `ssh-add` invocation, or a pause.
enum Step {
    SshAdd(&'static [&'static str], &'static str),
    Sleep(Duration),
}
use Step::{Sleep, SshAdd};

/// Keys generated by OpenSSH (see `ssh-add`'s tests for the same set):
/// `plain`, `rsa`, `ecdsa`, `nocomment`, `pem`, `enc` (passphrase `pw`),
/// `user` with `user-cert.pub`.
fn fixtures(openssh: &Openssh) -> TempDir {
    let dir = tempfile::tempdir().unwrap();
    let d = dir.path();
    let keygen = |args: &[&str]| {
        let out = run(
            command(openssh.require_tool("ssh-keygen"), d).args(args),
            b"",
        );
        assert_eq!(out.status, Some(0), "{args:?}: {}", out.stderr);
    };
    keygen(&[
        "-q",
        "-t",
        "ed25519",
        "-N",
        "",
        "-C",
        "plain key",
        "-f",
        "plain",
    ]);
    keygen(&[
        "-q", "-t", "rsa", "-b", "1024", "-N", "", "-C", "rsa", "-f", "rsa",
    ]);
    keygen(&[
        "-q", "-t", "ecdsa", "-b", "384", "-N", "", "-C", "ecdsa", "-f", "ecdsa",
    ]);
    keygen(&["-q", "-t", "ed25519", "-N", "", "-C", "", "-f", "nocomment"]);
    keygen(&[
        "-q", "-t", "rsa", "-b", "1024", "-m", "PEM", "-N", "", "-f", "pem",
    ]);
    keygen(&[
        "-q",
        "-t",
        "ed25519",
        "-N",
        "pw",
        "-C",
        "encrypted",
        "-f",
        "enc",
    ]);
    keygen(&["-q", "-t", "ed25519", "-N", "", "-C", "ca", "-f", "ca"]);
    keygen(&[
        "-q",
        "-t",
        "ed25519",
        "-N",
        "",
        "-C",
        "certified",
        "-f",
        "user",
    ]);
    keygen(&["-q", "-s", "ca", "-I", "user-id", "-n", "alice", "user.pub"]);
    dir
}

fn install(fixtures: &Path, dir: &Path) {
    for entry in fs::read_dir(fixtures).unwrap() {
        let entry = entry.unwrap();
        fs::copy(entry.path(), dir.join(entry.file_name())).unwrap();
    }
}

/// Run `steps` against a fresh agent (`program` with `agent_args`), using
/// OpenSSH's ssh-add as the client. Returns each ssh-add outcome.
fn session(
    openssh: &Openssh,
    fixtures: &Path,
    program: &Path,
    agent_args: &[&str],
    steps: &[Step],
) -> Vec<Outcome> {
    let dir = tempfile::tempdir().unwrap();
    install(fixtures, dir.path());
    let socket = dir.path().join("agent.sock");
    let agent = Agent::start_program(program, agent_args, &socket);
    let mut outcomes = Vec::new();
    for step in steps {
        match step {
            SshAdd(args, stdin) => outcomes.push(run(
                command(openssh.require_tool("ssh-add"), dir.path())
                    .env("SSH_AUTH_SOCK", &socket)
                    .args(*args),
                stdin.as_bytes(),
            )),
            Sleep(duration) => thread::sleep(*duration),
        }
    }
    drop(agent);
    outcomes
}

/// Run the session against both agents and compare every step.
fn compare(openssh: &Openssh, fixtures: &Path, agent_args: &[&str], steps: &[Step]) {
    let theirs = session(
        openssh,
        fixtures,
        &openssh.require_tool("ssh-agent"),
        agent_args,
        steps,
    );
    let ours = session(openssh, fixtures, Path::new(OURS), agent_args, steps);
    let commands = steps.iter().filter_map(|step| match step {
        SshAdd(args, _) => Some(args),
        Sleep(_) => None,
    });
    for ((args, ours), theirs) in commands.zip(&ours).zip(&theirs) {
        assert_eq!(
            (ours.status, &ours.stdout),
            (theirs.status, &theirs.stdout),
            "ssh-add {args:?} (agent args {agent_args:?})\nours: {}\nOpenSSH: {}",
            ours.stderr,
            theirs.stderr,
        );
    }
}

#[test]
fn adding_listing_and_removing() {
    let openssh = require_openssh!();
    let fixtures = fixtures(&openssh);
    compare(
        &openssh,
        fixtures.path(),
        &[],
        &[
            SshAdd(&["-l"], ""),
            SshAdd(&["plain", "rsa", "ecdsa", "nocomment", "pem", "user"], ""),
            SshAdd(&["enc"], "pw\n"),
            SshAdd(&["-l"], ""),
            SshAdd(&["-L"], ""),
            SshAdd(&["-l", "-E", "md5"], ""),
            // Re-adding keeps the position.
            SshAdd(&["plain"], ""),
            SshAdd(&["-l"], ""),
            SshAdd(&["-d", "rsa"], ""),
            SshAdd(&["-d", "rsa"], ""),
            SshAdd(&["-d", "user"], ""),
            SshAdd(&["-l"], ""),
            SshAdd(&["-D"], ""),
            SshAdd(&["-l"], ""),
        ],
    );
}

#[test]
fn signing() {
    let openssh = require_openssh!();
    let fixtures = fixtures(&openssh);
    compare(
        &openssh,
        fixtures.path(),
        &[],
        &[
            SshAdd(&["plain", "rsa", "ecdsa", "pem", "user"], ""),
            SshAdd(&["-T", "plain.pub", "rsa.pub", "ecdsa.pub", "user.pub"], ""),
            SshAdd(&["-T", "user-cert.pub"], ""),
            SshAdd(&["-T", "enc.pub"], ""),
            // Keys needing confirmation can't sign without a way to ask.
            SshAdd(&["-c", "enc"], "pw\n"),
            SshAdd(&["-T", "enc.pub"], ""),
        ],
    );
}

