#[test]
fn lifetimes() {
    let openssh = require_openssh!();
    let fixtures = fixtures(&openssh);
    let wait = Sleep(Duration::from_millis(2500));
    compare(
        &openssh,
        fixtures.path(),
        &[],
        &[
            SshAdd(&["-t", "1", "plain"], ""),
            SshAdd(&["rsa"], ""),
            SshAdd(&["-l"], ""),
            wait,
            SshAdd(&["-l"], ""),
        ],
    );
    // A default lifetime applies to keys added without one.
    compare(
        &openssh,
        fixtures.path(),
        &["-t", "1"],
        &[
            SshAdd(&["plain"], ""),
            SshAdd(&["-t", "1h", "rsa"], ""),
            Sleep(Duration::from_millis(2500)),
            SshAdd(&["-l"], ""),
        ],
    );
}

